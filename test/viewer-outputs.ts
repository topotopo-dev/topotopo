  check((await post({ ...request, replace: true })).status === 200 && !fs.existsSync(path.join(ws.exportDir, 'turbine_3.glb')), 'explicit replace keeps destination');
  check((await post({ ...request, name: '../escape' })).status === 400, 'export filename cannot escape root');
  check((await get('api/output/file?id=../../etc/passwd')).status === 404, 'downloads require known identifiers');
  check((await post({ ...request, options: { scale: -1 } })).status === 400, 'invalid export options rejected');
  const images = await post({ id: texture.id, revision: texture.revision, name: 'maps', format: 'textures', options: { layers: ['*'] } });
  check(images.status === 200, 'texture bundle exports all layers');
