import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';
import '../src/nodes/index.ts';
import { Engine } from '../src/graph/engine.ts';
import type { GraphSpec, NodeSpec } from '../src/graph/types.ts';
import { createNodeHost } from '../src/host/node.ts';
import { BUILTIN_LIBRARY } from '../src/config.ts';
import { readManifest } from '../src/package.ts';
import type { PackageManifest } from '../src/package.ts';
import { openPackages, publishPackage, publishText, publishedVersions, versionHash, workingHash } from '../src/packages/registry.ts';
import type { VersionInfo } from '../src/packages/registry.ts';
import { thumbOptions, thumbnailPNG as renderThumb } from '../src/render/preview.ts';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
/** The built-in library's folder in this repository. */
export const LIBRARY = BUILTIN_LIBRARY.path;
const README = path.join(ROOT, 'README.md');
const START = '<!-- builtin:start (generated by npm run builtin) -->';
const END = '<!-- builtin:end -->';
/** The graph a built-in package shows (its manifest's "graph"), whose output lines its outputs up: the package's default output. */
export const SHOWN = 'lineup';
/** Metres between two outputs of a line-up. */
export const GAP = 1;

/** An output of a built-in package's working folder: its name, the node type a graph names it with, its graph file. */
export interface BuiltinOutput { name: string; type: string; file: string; graph: GraphSpec }
/** A built-in package's working folder: its folder name, full name, manifest, outputs and published versions. */
export interface Builtin { name: string; package: string; dir: string; manifest: PackageManifest; outputs: BuiltinOutput[]; versions: VersionInfo[] }

/** Every package of the built-in library (their working folders, in this repository) with its outputs, by name. */
export function readBuiltin(): Builtin[] {
  return fs.readdirSync(LIBRARY, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort().map((name) => {
    const dir = path.join(LIBRARY, name), manifest = readManifest(dir), pkg = `topotopo/${name}`;
    const outputs = fs.readdirSync(path.join(dir, 'graphs')).filter((f) => f.endsWith('.json') && f !== `${SHOWN}.json`).sort().map((f) => ({
      name: f.slice(0, -'.json'.length), type: `${pkg}/${f.slice(0, -'.json'.length)}`, file: `library/${name}/graphs/${f}`,
      graph: JSON.parse(fs.readFileSync(path.join(dir, 'graphs', f), 'utf8')) as GraphSpec,
    }));
    return { name, package: pkg, dir, manifest, outputs, versions: publishedVersions(dir, pkg) };
  });
}

/** Node types used by a graph, including nested graphs (foreach/solver bodies). */
export function typesUsed(g: GraphSpec, out = new Set<string>()): Set<string> {
  for (const spec of Object.values(g.nodes ?? {})) {
    if (typeof spec?.type === 'string') out.add(spec.type);
    for (const v of Object.values(spec?.params ?? {})) if (v && typeof v === 'object' && (v as any).nodes) typesUsed(v as GraphSpec, out);
  }
  return out;
}

/** What a built-in package is said to hold: the end of its manifest's description ("…: walls, windows and doors"). */
export const builtinText = (k: Builtin) => k.manifest.description.replace(/^[^:]*:\s*/, '');

/**
 * What a built-in package's line-up is: the kind its outputs share, or a scene when they are of several kinds (src/graph/outputs.ts;
 * publishing checks it, as it checks every kind a built-in package pins).
 */
export const lineupKind = (k: Builtin) => {
  const kinds = new Set(k.outputs.map((o) => o.graph.outputs?.[o.name]?.kind));
  return kinds.size === 1 ? [...kinds][0] ?? 'scene' : 'scene';
};

/**
 * The graph a built-in package shows: each output at its defaults, side by side along +X in name order, from x = 0 with GAP metres
 * between them (`sizes`: each output's bounding box along X, as cooked). Its output "lineup" is the package's default
 * output, with its kind pinned and its tags.
 */
export function lineupGraph(k: Builtin, sizes: Map<string, [number, number]>): GraphSpec {
  const nodes: Record<string, NodeSpec> = {};
  let x = 0;
  for (const o of k.outputs) {
    const [min, max] = sizes.get(o.name)!;
    nodes[o.name] = { type: o.type };
    nodes[`${o.name}_at`] = { type: 'transform', in: [o.name], params: { translate: [+(x - min).toFixed(3), 0, 0] } };
    x += max - min + GAP;
  }
  nodes.lineup = { type: 'merge', in: k.outputs.map((o) => `${o.name}_at`) };
  return {
    description: `TopoTopo's ${k.name} package, its ${k.outputs.length} outputs side by side at their defaults. The package's default output and its preview, from ${k.outputs[0].name} to ${k.outputs.at(-1)!.name} along +X, ${GAP} m apart.`,
    nodes, output: 'lineup',
    outputs: { lineup: { node: 'lineup', label: `${k.manifest.title} line-up`, kind: lineupKind(k), tags: ['lineup', k.name] } },
  };
}
/** A line-up as its file holds it: one node per line. */
export const lineupText = (g: GraphSpec) => [
  '{',
  `  "description": ${JSON.stringify(g.description)},`,
  '  "nodes": {',
  Object.entries(g.nodes).map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n'),
  '  },',
  `  "output": ${JSON.stringify(g.output)},`,
  `  "outputs": ${JSON.stringify(g.outputs)}`,
  '}',
].join('\n') + '\n';

/** The README thumbnail tables (one per package, outputs by full name), between the markers. */
export function readmeBlock(all: Builtin[]): string {
  const lines: string[] = [START];
  const cols = 4;
  for (const k of all) {
    const v = k.versions.at(-1);
    lines.push('', `**${k.package}**${v ? ` ${v.version}` : ''}: ${builtinText(k)}`, '', '|' + ' |'.repeat(cols), '|' + '---|'.repeat(cols));
    for (let i = 0; i < k.outputs.length; i += cols) {
      const row = k.outputs.slice(i, i + cols).map((o) => `<img src="library/${k.name}/thumbs/${o.name}.png" width="120" alt="${o.type}"><br>\`${o.type}\``);
      while (row.length < cols) row.push('');
      lines.push('| ' + row.join(' | ') + ' |');
    }
  }
  lines.push('', END);
  return lines.join('\n');
}

/** README.md with the built-in packages block replaced (null when the markers are missing). */
export function readmeWithBlock(readme: string, block: string): string | null {
  const a = readme.indexOf(START), b = readme.indexOf(END);
  if (a < 0 || b < a) return null;
  return readme.slice(0, a) + block + readme.slice(b + END.length);
}

/** Stale derived files and unpublished or changed built-in packages ([] = up to date). */
export function checkBuiltin(all = readBuiltin()): string[] {
  const out: string[] = [];
  const readme = fs.readFileSync(README, 'utf8').replace(/\r\n/g, '\n');
  const want = readmeWithBlock(readme, readmeBlock(all));
  if (want === null) out.push('README.md has no built-in packages markers');
  else if (want !== readme) out.push('README.md built-in packages table is stale: run npm run builtin');
  for (const k of all) {
    for (const o of k.outputs) if (!fs.existsSync(path.join(k.dir, 'thumbs', `${o.name}.png`))) out.push(`library/${k.name}/thumbs/${o.name}.png is missing: run npm run builtin`);
    for (const v of k.versions) if (versionHash(path.join(k.dir, 'versions', v.version)) !== v.hash) out.push(`${k.package} ${v.version} was changed after publishing: its files no longer give the hash in its version.json`);
    const newest = k.versions.at(-1);
    if (!newest) out.push(`${k.package} has no published version: npm run builtin -- --publish ${k.name} --note "..."`);
    else if (workingHash(k.dir) !== newest.hash) out.push(`${k.package}: its working folder library/${k.name} differs from its newest version, ${newest.version}: publish the change, npm run builtin -- --publish ${k.name} --note "what changed"`);
  }
  return out;
}

/** A thumbnail: 256 px, deflate level 9 (the options live in src/render/preview.ts, shared with the web app). */
export const thumbnailPNG = (geo: any, g: GraphSpec): Uint8Array => renderThumb(geo, g, (d) => zlib.deflateSync(d, { level: 9 }));
export { thumbOptions };

/** An engine on a built-in package's working folder: its graphs name its outputs, which cook from those graphs as they are now. */
async function builtinEngine(k: Builtin) {
  const engine = new Engine(createNodeHost({ baseDir: k.dir }));
  await engine.init();
  const pk = openPackages(engine, k.dir);
  return { engine, pk };
}

// realpath on both sides: started through a symlinked path, argv[1] keeps the link while the module URL does not
if (process.argv[1] && fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url))) {
  const args = process.argv.slice(2);
  const opt = (f: string) => { const i = args.indexOf(f); return i >= 0 ? args[i + 1] : undefined; };
  const all = readBuiltin();
  const writeReadme = (list: Builtin[]) => {
    const readme = fs.readFileSync(README, 'utf8').replace(/\r\n/g, '\n');
    const nr = readmeWithBlock(readme, readmeBlock(list));
    if (nr === null) console.log(`README.md: add the built-in packages markers to get the thumbnail tables:\n${START}\n${END}`);
    else if (nr !== readme) fs.writeFileSync(README, nr);
  };
  if (args.includes('--check')) {
    const problems = checkBuiltin(all);
    for (const p of problems) console.log('FAIL ' + p);
    if (!problems.length) console.log(`built-in packages: thumbnails, README table and versions are up to date (${all.length} packages, ${all.reduce((s, k) => s + k.outputs.length, 0)} outputs)`);
    process.exit(problems.length ? 1 : 0);
  }
  if (args.includes('--publish')) {
    const name = opt('--publish'), k = all.find((x) => x.name === name);
    if (!k) { console.log(`--publish needs a built-in package: ${all.map((x) => x.name).join(', ')}`); process.exit(1); }
    // publishing cooks each output as a package that uses the built-in package does, in the package's own scope
    const { engine, pk } = await builtinEngine(k);
    const r = await publishPackage(pk, { note: opt('--note'), big: args.includes('--big'), builtin: true });
    console.log(publishText(r));
    if (r.ok) writeReadme(readBuiltin());
    await engine.host.pool?.close();
    process.exit(r.ok ? 0 : 1);
  }
  const filter = args.find((a) => !a.startsWith('--'));
  let failed = 0;
  for (const k of all) {
    const { engine } = await builtinEngine(k);
    const sizes = new Map<string, [number, number]>();
    fs.mkdirSync(path.join(k.dir, 'thumbs'), { recursive: true });
    for (const o of k.outputs) {
      engine.cache.clear();
      const r = await engine.cook({ nodes: { o: { type: o.type } }, output: 'o' });
      if (!r.ok || !r.geo) {
        failed++;
        console.log(`FAIL ${o.type}: ${r.errors.map((e) => `[${e.node}] ${e.message}`).join('; ')}`);
        continue;
      }
      const bb = r.geo.bbox(true);
      sizes.set(o.name, [bb.min[0], bb.max[0]]);
      if (filter && !o.name.includes(filter)) continue;
      const t0 = performance.now();
      fs.writeFileSync(path.join(k.dir, 'thumbs', `${o.name}.png`), thumbnailPNG(r.geo, o.graph));
      const warn = r.warnings.length ? `, ${r.warnings.length} warnings: ${r.warnings.slice(0, 2).map((w) => `[${w.node}] ${w.message}`).join('; ')}` : '';
      console.log(`ok   ${o.type.padEnd(36)} cook ${r.ms.toFixed(0).padStart(4)} ms, thumb ${(performance.now() - t0).toFixed(0).padStart(3)} ms, ${r.geo.numPoints} pts ${r.geo.numPrims} prims${warn}`);
    }
    if (sizes.size === k.outputs.length) {
      const file = path.join(k.dir, 'graphs', `${SHOWN}.json`), text = lineupText(lineupGraph(k, sizes));
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== text) { fs.writeFileSync(file, text); console.log(`wrote library/${k.name}/graphs/${SHOWN}.json (the line-up)`); }
    }
    await engine.host.pool?.close();
  }
  writeReadme(all);
  const stale = all.filter((k) => k.versions.at(-1)?.hash !== workingHash(k.dir)).map((k) => k.name);
  console.log(`\nbuilt-in packages: ${all.length} packages, ${all.reduce((s, k) => s + k.outputs.length, 0)} outputs, thumbnails, line-ups and README table written${failed ? `, ${failed} failed` : ''}`);
  if (stale.length) console.log(`not published yet: ${stale.join(', ')} (npm run builtin -- --publish <name> --note "what changed")`);
  process.exit(failed ? 1 : 0);
}
