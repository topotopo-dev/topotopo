// The asset shelf: shelf/<name>.json are graph assets the engine registers as node types (category "shelf").
// This script keeps the derived files in step with them:
//   shelf/index.json         the asset list the engine reads through its Host (dependencies first)
//   shelf/thumbs/<name>.png  a 256 px matcap thumbnail of each asset cooked at its defaults (no view label or gizmo)
//   README.md                the thumbnail table between the shelf markers
//
//   node scripts/gen-shelf.ts             write all three, print cook and render times
//   node scripts/gen-shelf.ts stairs      only re-render thumbnails whose names contain "stairs"
//   node scripts/gen-shelf.ts --check     exit 1 when index.json or the README table is stale (test/shelf.ts runs it)
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';
import '../src/nodes/index.ts';
import { Engine } from '../src/graph/engine.ts';
import { getNodeDef } from '../src/graph/registry.ts';
import { SHELF_DIR, createNodeHost } from '../src/host/node.ts';
import type { GraphSpec } from '../src/graph/types.ts';
import { thumbOptions, thumbnailPNG as renderThumb } from '../src/render/preview.ts';

export { SHELF_DIR };
export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const THUMB_DIR = path.join(SHELF_DIR, 'thumbs');
const README = path.join(ROOT, 'README.md');
const START = '<!-- shelf:start (generated by npm run shelf) -->';
const END = '<!-- shelf:end -->';
/** Shelf sections in README order (an asset's meta.shelf_group). */
export const GROUPS = ['architecture', 'props', 'terrain'];

export interface ShelfFile { name: string; file: string; graph: GraphSpec }

/** Every shelf/<name>.json (not index.json), sorted by name. */
export function readShelfFiles(): ShelfFile[] {
  return fs.readdirSync(SHELF_DIR)
    .filter((f) => f.endsWith('.json') && f !== 'index.json')
    .sort()
    .map((f) => ({ name: path.basename(f, '.json'), file: f, graph: JSON.parse(fs.readFileSync(path.join(SHELF_DIR, f), 'utf8')) }));
}

/** Node types used by a graph, including nested graphs (foreach/solver bodies). */
export function typesUsed(g: GraphSpec, out = new Set<string>()): Set<string> {
  for (const spec of Object.values(g.nodes ?? {})) {
    if (typeof spec?.type === 'string') out.add(spec.type);
    for (const v of Object.values(spec?.params ?? {})) if (v && typeof v === 'object' && (v as any).nodes) typesUsed(v as GraphSpec, out);
  }
  return out;
}

/** Shelf files with every shelf asset an asset uses listed before it (then by name). */
export function dependencyOrder(files: ShelfFile[]): ShelfFile[] {
  const byName = new Map(files.map((f) => [f.name, f]));
  const out: ShelfFile[] = [], state = new Map<string, number>();
  const visit = (f: ShelfFile, trail: string[]) => {
    const s = state.get(f.name);
    if (s === 2) return;
    if (s === 1) throw new Error(`shelf assets use each other in a cycle: ${[...trail, f.name].join(' → ')}`);
    state.set(f.name, 1);
    for (const t of [...typesUsed(f.graph)].sort()) {
      const dep = byName.get(t);
      if (dep && dep !== f && !getNodeDef(t)) visit(dep, [...trail, f.name]);
    }
    state.set(f.name, 2);
    out.push(f);
  };
  for (const f of files) visit(f, []);
  return out;
}

/** The content of shelf/index.json. */
export function indexText(files: ShelfFile[]): string {
  const assets = dependencyOrder(files).map((f) => ({ name: f.name, file: f.file, group: f.graph.meta?.shelf_group ?? 'props' }));
  return JSON.stringify({ generated: 'by scripts/gen-shelf.ts (npm run shelf); the engine registers these in order', assets }, null, 1) + '\n';
}

/** The README thumbnail tables (one per group), between the markers. */
export function readmeBlock(files: ShelfFile[]): string {
  const lines: string[] = [START];
  const cols = 6;
  for (const grp of GROUPS) {
    const list = files.filter((f) => (f.graph.meta?.shelf_group ?? 'props') === grp);
    if (!list.length) continue;
    lines.push('', `**${grp}**`, '', '|' + ' |'.repeat(cols), '|' + '---|'.repeat(cols));
    for (let i = 0; i < list.length; i += cols) {
      const row = list.slice(i, i + cols).map((f) => `<img src="shelf/thumbs/${f.name}.png" width="120" alt="${f.name}"><br>\`${f.name}\``);
      while (row.length < cols) row.push('');
      lines.push('| ' + row.join(' | ') + ' |');
    }
  }
  lines.push('', END);
  return lines.join('\n');
}

/** README.md with the shelf block replaced (null when the markers are missing). */
export function readmeWithBlock(readme: string, block: string): string | null {
  const a = readme.indexOf(START), b = readme.indexOf(END);
  if (a < 0 || b < a) return null;
  return readme.slice(0, a) + block + readme.slice(b + END.length);
}

/** Stale derived files ([] = up to date). */
export function checkShelf(files = readShelfFiles()): string[] {
  const out: string[] = [];
  const idx = path.join(SHELF_DIR, 'index.json');
  const have = fs.existsSync(idx) ? fs.readFileSync(idx, 'utf8').replace(/\r\n/g, '\n') : null;
  if (have !== indexText(files)) out.push('shelf/index.json is stale: run npm run shelf');
  const readme = fs.readFileSync(README, 'utf8').replace(/\r\n/g, '\n');
  const want = readmeWithBlock(readme, readmeBlock(files));
  if (want === null) out.push('README.md has no shelf markers');
  else if (want !== readme) out.push('README.md shelf table is stale: run npm run shelf');
  for (const f of files) if (!fs.existsSync(path.join(THUMB_DIR, `${f.name}.png`))) out.push(`shelf/thumbs/${f.name}.png is missing: run npm run shelf`);
  return out;
}

/** A shelf thumbnail: 256 px, deflate level 9 (the options live in src/render/preview.ts, shared with the gallery). */
export const thumbnailPNG = (geo: any, g: GraphSpec): Uint8Array => renderThumb(geo, g, (d) => zlib.deflateSync(d, { level: 9 }));
export { thumbOptions };

// realpath on both sides: started through a symlinked path, argv[1] keeps the link while the module URL does not
if (process.argv[1] && fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url))) {
  const args = process.argv.slice(2);
  const filter = args.find((a) => !a.startsWith('--'));
  const files = readShelfFiles();
  if (args.includes('--check')) {
    const problems = checkShelf(files);
    for (const p of problems) console.log('FAIL ' + p);
    if (!problems.length) console.log(`shelf: index.json, thumbnails and README table are up to date (${files.length} assets)`);
    process.exit(problems.length ? 1 : 0);
  }
  fs.mkdirSync(THUMB_DIR, { recursive: true });
  fs.writeFileSync(path.join(SHELF_DIR, 'index.json'), indexText(files));
  const readme = fs.readFileSync(README, 'utf8').replace(/\r\n/g, '\n');
  const nr = readmeWithBlock(readme, readmeBlock(files));
  if (nr === null) console.log(`README.md: add the shelf markers to get the thumbnail table:\n${START}\n${END}`);
  else if (nr !== readme) fs.writeFileSync(README, nr);

  const engine = new Engine(createNodeHost({ baseDir: SHELF_DIR, shelf: false }));
  await engine.init();
  const res = await engine.loadShelf(SHELF_DIR);
  for (const e of res.errors) console.log('FAIL ' + e);
  let failed = res.errors.length;
  for (const f of files) {
    if (filter && !f.name.includes(filter)) continue;
    if (!engine.assets.has(f.name)) continue;
    const graph: GraphSpec = { nodes: { asset: { type: f.name } }, output: 'asset' };
    engine.cache.clear();
    const r = await engine.cook(graph);
    if (!r.ok || !r.geo) {
      failed++;
      console.log(`FAIL ${f.name}: ${r.errors.map((e) => `[${e.node}] ${e.message}`).join('; ')}`);
      continue;
    }
    const t0 = performance.now();
    fs.writeFileSync(path.join(THUMB_DIR, `${f.name}.png`), thumbnailPNG(r.geo, f.graph));
    const warn = r.warnings.length ? `, ${r.warnings.length} warnings: ${r.warnings.slice(0, 2).map((w) => `[${w.node}] ${w.message}`).join('; ')}` : '';
    console.log(`ok   ${f.name.padEnd(16)} cook ${r.ms.toFixed(0).padStart(4)} ms, thumb ${(performance.now() - t0).toFixed(0).padStart(3)} ms, ${r.geo.numPoints} pts ${r.geo.numPrims} prims${warn}`);
  }
  console.log(`\nshelf: ${files.length} assets, index.json + README table written${failed ? `, ${failed} failed` : ''}`);
  process.exit(failed ? 1 : 0);
}
