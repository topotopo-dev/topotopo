const glyphs = new Map<string, number[]>();
for (const [k, v] of Object.entries(G)) glyphs.set(k, v.split(' ').map((r) => parseInt(r, 2)));

export const GLYPH_W = 6; // 5 + 1 spacing
export const GLYPH_H = 8;

/** Draw text into an RGB float buffer. scale = pixel size of one font dot. */
export function drawText(buf: Float32Array, W: number, H: number, x: number, y: number, text: string, color: number[], scale = 1, shadow = true) {
  const put = (px: number, py: number, c: number[]) => {
    if (px < 0 || py < 0 || px >= W || py >= H) return;
    const i = (py * W + px) * 3;
    buf[i] = c[0]; buf[i + 1] = c[1]; buf[i + 2] = c[2];
  };
  const draw = (ox: number, oy: number, c: number[]) => {
    let cx = ox;
    for (const ch of text) {
      const rows = glyphs.get(ch) ?? glyphs.get(ch.toUpperCase()) ?? glyphs.get('?')!;
      for (let r = 0; r < 7; r++)
        for (let col = 0; col < 5; col++)
          if (rows[r] & (1 << (4 - col)))
            for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) put(cx + col * scale + sx, oy + r * scale + sy, c);
      cx += GLYPH_W * scale;
    }
  };
  if (shadow) draw(x + scale, y + scale, [0, 0, 0]);
  draw(x, y, color);
}

export function textWidth(text: string, scale = 1) {
  return [...text].length * GLYPH_W * scale;
}
